//! `memory_recent --hook-session-start --brief`: the SessionStart opening
//! brief (implementation-001).
//!
//! With `--brief`, the fixed "3 session ids" identity block is replaced by a
//! fenced opening brief: same-project session cards carrying the last usable
//! user request and the assistant stop point, plus title-only lines for other
//! projects. The brief is generated once and written whole: UTF-8 without
//! BOM, LF line endings, exactly one final newline — and every failure still
//! exits 0 with empty stdout and one stderr line, exactly like the identity
//! block it extends.
//!
//! Rules baked into this module (implementation-001 §2–§7):
//! * the project identity is a normalized filesystem-derived key, so two cwd
//!   strings name the same project when [`project_key`] is equal — never when
//!   the strings match;
//! * history text is data, never instructions: every text field is
//!   whitespace-folded, clipped, and defused so a literal
//!   `<agent-memory-brief` can never reappear inside the fence it would fake;
//! * the brief reads only through [`memory_recent_with`] — there is no raw
//!   record path here — and budgets are enforced by dropping whole cards or
//!   whole entries, never by cutting one in half;
//! * `--log` appends one metadata-only JSON line per finished run: counts and
//!   a project-key hash, never a title, a path or transcript text.

