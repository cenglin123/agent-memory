/// The last usable user request in the tail (newest first). A turn that only
/// carries host bookkeeping is skipped, and an older human request wins.
fn usable_user_request(tail: &[RecentTailTurn]) -> Option<String> {
    tail.iter()
        .rev()
        .filter(|turn| turn.role == ROLE_USER)
        .find_map(|turn| usable_request_text(&turn.text))
}

/// §4: strip leading host reminders and this system's older injection
/// blocks, then require a non-empty, non-bookkeeping text that does not carry
/// the brief fence marker.
fn usable_request_text(raw: &str) -> Option<String> {
    let stripped = strip_leading_blocks(raw);
    let trimmed = stripped.trim();
    if trimmed.is_empty() {
        return None;
    }
    if FORBIDDEN_REQUEST_PREFIXES.iter().any(|prefix| trimmed.starts_with(prefix)) {
        return None;
    }
    if trimmed.contains("<agent-memory-brief") {
        return None;
    }
    Some(trimmed.to_string())
}

/// Repeatedly removes leading `<system-reminder>` blocks and the two injection
/// blocks written by earlier agent-memory versions, together with trailing
/// whitespace. A complete old block is removed without sacrificing a real
/// request that follows it in the same user turn. An unterminated old block
/// makes the whole turn unusable; an unterminated reminder keeps its text.
fn strip_leading_blocks(text: &str) -> &str {
    const REMINDER_OPEN: &str = "<system-reminder>";
    const REMINDER_CLOSE: &str = "</system-reminder>";
    const OWN_BLOCKS: [(&str, &str); 2] = [
        (HOOK_HEADER, HOOK_FOOTER),
        (COORDINATION_ZONE_START_LINE, COORDINATION_ZONE_END_LINE),
    ];
    let mut current = text;
    'blocks: loop {
        let rest = current.trim_start();
        if rest.starts_with(REMINDER_OPEN) {
            let Some(end) = rest.find(REMINDER_CLOSE) else {
                return rest;
            };
            current = &rest[end + REMINDER_CLOSE.len()..];
            continue;
        }
        for (open, close) in OWN_BLOCKS {
            if rest.starts_with(open) {
                let Some(end) = rest.find(close) else {
                    return "";
                };
                current = &rest[end + close.len()..];
                continue 'blocks;
            }
        }
        return rest;
    }
}

/// 「停在哪里」: the trimmed text of the last assistant turn. Missing, empty,
/// or fence-carrying assistant turns mean the field is absent.
fn stopped_at(tail: &[RecentTailTurn]) -> Option<String> {
    let turn = tail.iter().rev().find(|turn| turn.role == ROLE_ASSISTANT)?;
    let trimmed = turn.text.trim();
    if trimmed.is_empty() || trimmed.contains("<agent-memory-brief") {
        return None;
    }
    Some(trimmed.to_string())
}

/// The waiting marker fires only when the stop point — whitespace folded —
/// ends with an ASCII or fullwidth question mark.
fn ends_with_question(folded: &str) -> bool {
    folded.ends_with('?') || folded.ends_with('？')
}

/// Collapses every run of whitespace (newlines included) into one space.
fn fold_whitespace(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut in_whitespace = false;
    for ch in text.chars() {
        if ch.is_whitespace() {
            if !in_whitespace {
                out.push(' ');
                in_whitespace = true;
            }
        } else {
            out.push(ch);
            in_whitespace = false;
        }
    }
    out
}

/// Defuses the fence markers so no field can reproduce the brief's own
/// envelope verbatim. This is plain-text hygiene, not a promise that every
/// visual homoglyph is unrecognizable to a model.
fn sanitize_fence(text: &str) -> String {
    // Invisible and bidi-control characters are dropped first, so a marker
    // split by one cannot slip past the literal match and still read as the
    // fence to a model. Fullwidth angle brackets are folded to ASCII.
    let text: String = text
        .chars()
        .filter(|ch| {
            !matches!(
                ch,
                '\u{200b}'..='\u{200f}'
                    | '\u{202a}'..='\u{202e}'
                    | '\u{2060}'..='\u{2064}'
                    | '\u{2066}'..='\u{2069}'
                    | '\u{feff}'
                    | '\u{00ad}'
            )
        })
        .map(|ch| match ch {
            '\u{ff1c}' => '<',
            '\u{ff1e}' => '>',
            other => other,
        })
        .collect();
    // ASCII case folding preserves byte offsets, so the original spelling is
    // retained and only a zero-width space is inserted after each marker.
    let folded = text.to_ascii_lowercase();
    let mut insertions: Vec<usize> = ["<agent-memory-brief", "</agent-memory-brief"]
        .iter()
        .flat_map(|marker| {
            folded
                .match_indices(marker)
                .map(|(index, _)| index + marker.len())
                .collect::<Vec<_>>()
        })
        .collect();
    insertions.sort_unstable();
    insertions.dedup();
    let mut out = String::with_capacity(text.len() + insertions.len() * 3);
    let mut previous = 0;
    for index in insertions {
        out.push_str(&text[previous..index]);
        out.push('\u{200b}');
        previous = index;
    }
    out.push_str(&text[previous..]);
    out
}

/// Everything that enters the output: fold, then defuse.
fn clean_text(text: &str) -> String {
    sanitize_fence(fold_whitespace(text).trim())
}

/// Clip by Unicode scalar count; an over-long text keeps `n - 1` scalars and
/// gains a single `…`.
fn clip(text: &str, max_chars: usize) -> String {
    if max_chars == 0 {
        return String::new();
    }
    if text.chars().count() <= max_chars {
        return text.to_string();
    }
    let mut out: String = text.chars().take(max_chars - 1).collect();
    out.push('…');
    out
}

fn char_count(text: &str) -> usize {
    text.chars().count()
}

