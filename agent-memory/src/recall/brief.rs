/// The metadata-only JSON line for one run: counts, timing and a project-key
/// hash, never a title, a path or transcript text. `host` is the validated
/// caller name (the CLI's whitelist is what keeps this a safe token).
fn brief_log_line(
    now_ms: Option<i64>,
    result: &Result<BriefOutcome, String>,
    elapsed_ms: u64,
    host: &str,
) -> String {
    let clock = now_ms.unwrap_or_else(|| chrono::Utc::now().timestamp_millis());
    let ts = rfc3339(clock)
        .unwrap_or_else(|| chrono::Utc::now().to_rfc3339_opts(chrono::SecondsFormat::Secs, true));
    let late_sources: Vec<String> = result
        .as_ref()
        .map(|outcome| outcome.late_sources.clone())
        .unwrap_or_default();
    let (outcome, reason, session_id, project_key, same_cards, other_items, chars) = match result {
        Ok(outcome) => (
            "ok",
            None,
            outcome.session_id.clone(),
            outcome.project_key.clone(),
            outcome.same_cards,
            outcome.other_items,
            char_count(&outcome.text),
        ),
        Err(message) => (
            "error",
            Some(sanitize_stderr(message)),
            None,
            None,
            0,
            0,
            0,
        ),
    };
    let line = json!({
        "ts": ts,
        "event": "brief",
        "host": clean_text(host),
        "session_id": session_id,
        "project_key_sha256": project_key.as_deref().map(|key| sha256_hex(key.as_bytes())),
        "same_project_cards": same_cards,
        "other_project_items": other_items,
        "chars": chars,
        "late_sources": late_sources,
        "elapsed_ms": elapsed_ms,
        "outcome": outcome,
        "reason": reason,
    });
    line.to_string()
}

