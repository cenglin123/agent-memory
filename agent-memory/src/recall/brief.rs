/// The normalized project key for a cwd. Two cwds belong to the same project
/// exactly when their keys are equal.
///
/// The project root is found by walking up from `cwd` (at most
/// [`PROJECT_ROOT_MAX_LEVELS`] levels) to the innermost `.git` entry; a
/// `.git` *file* whose `gitdir` points into `<main>/.git/worktrees/<name>`
/// and whose main repository exists re-roots the project at that main
/// repository. Without any `.git` the cwd itself is the project root. Every
/// IO error on the way counts as "not found" and never panics.
pub fn project_key(cwd: &Path) -> String {
    normalize_path(&project_root(cwd))
}

/// The human-facing project name: the project root's last directory name (or
/// the drive for a drive root), before key normalization, after cleaning.
pub fn project_display(cwd: &Path) -> Option<String> {
    let root = project_root(cwd);
    let name = match root.file_name() {
        Some(name) => name.to_string_lossy().to_string(),
        None => root
            .to_string_lossy()
            .trim_end_matches(['/', '\\'])
            .to_string(),
    };
    let cleaned = clean_text(&name);
    (!cleaned.is_empty()).then_some(cleaned)
}

/// What one level of the upward walk decided.
enum GitAnchor {
    /// This level is the project root (or re-rooted at the named main repo).
    Root(PathBuf),
    /// No usable `.git` here; keep walking up.
    Missing,
}

fn project_root(cwd: &Path) -> PathBuf {
    let mut level: &Path = cwd;
    for _ in 0..PROJECT_ROOT_MAX_LEVELS {
        if let GitAnchor::Root(root) = git_anchor(level) {
            return root;
        }
        match level.parent() {
            Some(parent) => level = parent,
            None => break,
        }
    }
    cwd.to_path_buf()
}

fn git_anchor(level: &Path) -> GitAnchor {
    let dot_git = level.join(".git");
    // Any IO error here (missing entry, unreadable metadata) is "not found".
    let Ok(meta) = std::fs::symlink_metadata(&dot_git) else {
        return GitAnchor::Missing;
    };
    if meta.is_dir() {
        // Only a real repository anchors a project. Tools drop bare `.git`
        // directories without a `HEAD` (e.g. a snapshot store at a drive
        // root); treating those as a repo would fold every directory below
        // into one project.
        if dot_git.join("HEAD").is_file() {
            return GitAnchor::Root(level.to_path_buf());
        }
        return GitAnchor::Missing;
    }
    if !meta.is_file() {
        return GitAnchor::Missing;
    }
    // A `.git` file is a gitdir pointer. An unreadable file is "not found";
    // a readable file without a gitdir line still anchors a repo here.
    let Ok(content) = std::fs::read_to_string(&dot_git) else {
        return GitAnchor::Missing;
    };
    let first_line = content.lines().next().unwrap_or_default().trim();
    let Some(target) = first_line
        .strip_prefix("gitdir:")
        .map(str::trim)
        .filter(|value| !value.is_empty())
    else {
        return GitAnchor::Root(level.to_path_buf());
    };
    let target_path = {
        let path = Path::new(target);
        if path.is_absolute() {
            path.to_path_buf()
        } else {
            level.join(path)
        }
    };
    match worktree_main_repo(&target_path) {
        Some(main) => GitAnchor::Root(main),
        None => GitAnchor::Root(level.to_path_buf()),
    }
}

/// If `gitdir` resolves into a `.git/worktrees/<name>` layout, the directory
/// holding that `.git` is the main repository — and only when it exists.
fn worktree_main_repo(gitdir: &Path) -> Option<PathBuf> {
    let text = gitdir.to_string_lossy().to_string();
    let stripped = text.strip_prefix(r"\\?\").unwrap_or(&text);
    let stripped = match stripped.strip_prefix(r"UNC\") {
        Some(rest) => format!(r"\\{rest}"),
        None => stripped.to_string(),
    };
    // Split into (start, end, segment) so the main repo keeps its original
    // case and any `\\server\share` prefix.
    let mut segments: Vec<(usize, usize, &str)> = Vec::new();
    let mut start = 0usize;
    for (index, ch) in stripped.char_indices() {
        if ch == '/' || ch == '\\' {
            if index > start {
                segments.push((start, index, &stripped[start..index]));
            }
            start = index + 1;
        }
    }
    if start < stripped.len() {
        segments.push((start, stripped.len(), &stripped[start..]));
    }
    for window in segments.windows(3) {
        let [dot_git, worktrees, name] = window else {
            continue;
        };
        let is_worktree_layout = dot_git.2.eq_ignore_ascii_case(".git")
            && worktrees.2.eq_ignore_ascii_case("worktrees")
            && !name.2.is_empty();
        if !is_worktree_layout {
            continue;
        }
        // The main repository is the directory one level *before* the `.git`
        // segment; if `.git` is the first segment there is no such level.
        if dot_git.0 == 0 {
            return None;
        }
        let main = PathBuf::from(&stripped[..dot_git.0 - 1]);
        return std::fs::metadata(&main).is_ok().then_some(main);
    }
    None
}

/// §2.2, purely lexical: strip the `\\?\` (or `\\?\UNC\`) prefix, normalize
/// separators, fold `.` and `..`, drop trailing separators (a drive root
/// keeps `c:`), and fold case. The path is not resolved against the
/// filesystem, so two spellings that reach one directory through a link or a
/// substituted drive stay two projects.
fn normalize_path(path: &Path) -> String {
    let text = path.to_string_lossy().replace('/', "\\");
    let text = match text.strip_prefix(r"\\?\UNC\") {
        Some(rest) => format!(r"\\{rest}"),
        None => text.strip_prefix(r"\\?\").unwrap_or(&text).to_string(),
    };
    let (prefix, body) = match text.strip_prefix(r"\\") {
        Some(rest) => (r"\\", rest),
        None => match text.strip_prefix('\\') {
            Some(rest) => ("\\", rest),
            None => ("", text.as_str()),
        },
    };
    let mut parts: Vec<&str> = Vec::new();
    for segment in body.split('\\') {
        match segment {
            "" | "." => {}
            ".." => {
                // Never climb above a drive root (or out of the path).
                if parts.last().is_some_and(|last| !last.ends_with(':')) {
                    parts.pop();
                }
            }
            other => parts.push(other),
        }
    }
    format!("{prefix}{}", parts.join("\\")).to_lowercase()
}

