/// Whether a same-project card would say anything beyond its id and time.
fn has_card_content(session: &RecentSession) -> bool {
    session
        .title
        .as_deref()
        .is_some_and(|title| !clean_text(title).is_empty())
        || usable_user_request(&session.tail).is_some()
        || stopped_at(&session.tail).is_some()
}

/// Builds the whole brief from the merged sessions: candidate selection
/// (§5), text cleaning (§4), assembly and budget trimming (§6). `host` names
/// the caller and is cleaned like every other field before printing.
fn render_brief(
    sessions: &[RecentSession],
    late_sources: &[String],
    session_id: Option<&str>,
    cwd: Option<&Path>,
    now_ms: i64,
    host: &str,
) -> BriefOutcome {
    let current_key = cwd.map(project_key);
    // Each key walks up to 64 ancestor levels on disk; sessions of one
    // project share a cwd, so resolve every distinct cwd once.
    let mut keys: HashMap<&str, String> = HashMap::new();
    let candidates: Vec<&RecentSession> = sessions
        .iter()
        .filter(|session| {
            session
                .last_activity_local
                .as_deref()
                .is_some_and(|value| !value.is_empty())
        })
        .collect();

    // Same-project cards: the first 3 candidates whose project key matches
    // the current cwd; everything else stays in the "other" pool in order.
    let mut same: Vec<&RecentSession> = Vec::new();
    let mut rest: Vec<&RecentSession> = Vec::new();
    for session in candidates {
        let same_project = match (&current_key, session.cwd.as_deref()) {
            (Some(key), Some(value)) if !value.is_empty() => {
                keys.entry(value)
                    .or_insert_with(|| project_key(Path::new(value)))
                    == key
            }
            _ => false,
        };
        if same_project {
            // Overflow beyond the card limit is dropped: a same-project
            // session must never be listed under "other projects".
            // A session with no title, no usable request and no stop
            // point would be a bare id line, so it does not take a slot.
            if same.len() < SAME_PROJECT_CARDS && has_card_content(session) {
                same.push(session);
            }
        } else {
            rest.push(session);
        }
    }
    // Other-project entries: newest first, active within the last 7 days,
    // one when the same-project section is full, two otherwise.
    let quota = if same.len() == SAME_PROJECT_CARDS {
        1
    } else {
        2
    };
    let others: Vec<&RecentSession> = rest
        .iter()
        .filter(|session| activity_within(session, now_ms, OTHER_PROJECT_WINDOW_MS))
        .take(quota)
        .copied()
        .collect();

    let mut cards: Vec<String> = same
        .iter()
        .map(|session| {
            let request = usable_user_request(&session.tail);
            let stop = stopped_at(&session.tail);
            render_same_card(session, request.as_deref(), stop.as_deref())
        })
        .collect();
    let mut other_lines: Vec<String> = others.iter().map(|session| render_other_line(session)).collect();

    let mut text = assemble(&cards, &other_lines, late_sources, session_id, cwd, host);
    // Budget: whole entries first, then whole cards, from the back; the fixed
    // lines are never removed and no card is ever cut.
    while char_count(&text) > BRIEF_MAX_CHARS
        || cards.iter().any(|card| char_count(card) > CARD_MAX_CHARS)
    {
        if !other_lines.is_empty() {
            other_lines.pop();
        } else if !cards.is_empty() {
            cards.pop();
        } else {
            break;
        }
        text = assemble(&cards, &other_lines, late_sources, session_id, cwd, host);
    }

    BriefOutcome {
        text,
        session_id: session_id.map(str::to_string),
        project_key: current_key,
        same_cards: cards.len(),
        other_items: other_lines.len(),
        late_sources: late_sources.to_vec(),
    }
}

/// The byte template. Section headers follow the final card list, so a budget
/// trim that empties a section also removes (or rewrites) its header.
fn assemble(
    cards: &[String],
    others: &[String],
    late_sources: &[String],
    session_id: Option<&str>,
    cwd: Option<&Path>,
    host: &str,
) -> String {
    let mut text = String::new();
    text.push_str(BRIEF_OPEN);
    text.push('\n');
    text.push_str(BRIEF_EXPLANATION);
    text.push('\n');
    text.push_str("本会话：");
    // The host is a caller-supplied string: it goes through the same
    // cleaning as every other field, so only a whitelisted, defused name is
    // ever printed.
    text.push_str(&clean_text(host));
    text.push(' ');
    text.push_str(&clean_text(session_id.unwrap_or(HOOK_UNKNOWN_SESSION)));
    text.push('\n');
    let current = cwd
        .and_then(project_display)
        .filter(|value| !value.is_empty())
        .unwrap_or_else(|| UNKNOWN_PROJECT.to_string());
    text.push_str("当前项目：");
    text.push_str(&current);
    text.push('\n');
    if !late_sources.is_empty() {
        text.push_str(LATE_SOURCES_LABEL);
        let names: Vec<String> = late_sources.iter().map(|name| clean_text(name)).collect();
        text.push_str(&names.join("、"));
        text.push_str("）\n");
    }
    if cards.is_empty() {
        text.push_str(SAME_EMPTY);
        text.push('\n');
    } else {
        text.push_str(SAME_HEADER);
        text.push('\n');
        for card in cards {
            text.push_str(card);
        }
    }
    if !others.is_empty() {
        text.push_str(OTHER_HEADER);
        text.push('\n');
        for line in others {
            text.push_str(line);
        }
    }
    text.push_str(BRIEF_CLOSE);
    text.push('\n');
    text
}

/// One same-project card: the headline, the last usable user request, the
/// assistant stop point, and the waiting-for-an-answer marker (§6).
fn render_same_card(session: &RecentSession, request: Option<&str>, stop: Option<&str>) -> String {
    let title = session
        .title
        .as_deref()
        .map(clean_text)
        .filter(|value| !value.is_empty());
    let title = match title {
        Some(value) => clip(&value, 60),
        // A missing title falls back to the request on the card line only;
        // the "other project" list never substitutes anything.
        None => match request {
            Some(value) => clip(&clean_text(value), 60),
            None => UNTITLED.to_string(),
        },
    };
    let mut card = String::new();
    card.push_str(&format!(
        "- [{}] {}（{}，{}）\n",
        clean_text(&session.source),
        title,
        session.last_activity_local.as_deref().unwrap_or_default(),
        clean_text(&session.session_id),
    ));
    if let Some(value) = request {
        card.push_str(REQUEST_LABEL);
        card.push_str(&clip(&clean_text(value), 120));
        card.push('\n');
    }
    if let Some(value) = stop {
        card.push_str(STOP_LABEL);
        card.push_str(&clip(&clean_text(value), 160));
        card.push('\n');
    }
    if let Some(value) = stop {
        if ends_with_question(&fold_whitespace(value)) {
            card.push_str(WAITING_QUESTION);
            card.push('\n');
        }
    }
    card
}

/// One "other project" entry: source, local time, project display name and —
/// when present — the title only. No request text, no stop text, no fallback.
fn render_other_line(session: &RecentSession) -> String {
    let display = session
        .cwd
        .as_deref()
        .filter(|value| !value.is_empty())
        .and_then(|value| project_display(Path::new(value)))
        .unwrap_or_else(|| UNKNOWN_PROJECT_ENTRY.to_string());
    let mut line = format!(
        "- [{}] {} {}",
        clean_text(&session.source),
        session.last_activity_local.as_deref().unwrap_or_default(),
        display,
    );
    let title = session
        .title
        .as_deref()
        .map(clean_text)
        .filter(|value| !value.is_empty());
    if let Some(title) = title {
        line.push(' ');
        line.push_str(&clip(&title, 40));
    }
    line.push('\n');
    line
}

/// Whether the session's own activity clock falls inside the last `days`
/// days. An unparsable clock means "not inside" — nothing is invented.
fn activity_within(session: &RecentSession, now_ms: i64, window_ms: i64) -> bool {
    let bound = now_ms.saturating_sub(window_ms);
    for stamp in [
        session.last_activity_at.as_deref(),
        session.last_activity_local.as_deref(),
    ] {
        if let Some(stamp) = stamp {
            if let Ok(parsed) = chrono::DateTime::parse_from_rfc3339(stamp) {
                return parsed.timestamp_millis() >= bound;
            }
        }
    }
    false
}

