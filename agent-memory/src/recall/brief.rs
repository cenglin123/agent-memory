/// Reads the SessionStart JSON from stdin and returns `(session_id, cwd)`.
/// Anything that is not a bounded JSON object with usable fields means
/// `None` for that field; the run continues either way.
fn read_stdin_payload() -> (Option<String>, Option<PathBuf>) {
    use std::io::{IsTerminal, Read};
    let stdin = std::io::stdin();
    if stdin.is_terminal() {
        return (None, None);
    }
    let mut buffer = Vec::new();
    if stdin
        .lock()
        .take((HOOK_STDIN_MAX_BYTES as u64) + 1)
        .read_to_end(&mut buffer)
        .is_err()
    {
        return (None, None);
    }
    if buffer.len() > HOOK_STDIN_MAX_BYTES {
        return (None, None);
    }
    let Ok(text) = String::from_utf8(buffer) else {
        return (None, None);
    };
    parse_session_payload(&text)
}

/// Parses one SessionStart payload. `session_id` reuses the identity block's
/// strict validation; `cwd` accepts any non-empty string field (missing or
/// empty means the unknown directory).
fn parse_session_payload(input: &str) -> (Option<String>, Option<PathBuf>) {
    // PowerShell 5.1 may prefix a piped payload with a UTF-8 BOM.
    let text = input.trim_start_matches('\u{feff}').trim();
    if text.is_empty() {
        return (None, None);
    }
    let session_id = crate::recall::recent_hook::parse_session_id(text);
    let cwd = serde_json::from_str::<serde_json::Value>(text)
        .ok()
        .and_then(|value| value.as_object().and_then(|object| object.get("cwd")).cloned())
        .and_then(|value| value.as_str().map(str::to_string))
        .filter(|value| !value.is_empty())
        .map(PathBuf::from);
    (session_id, cwd)
}

